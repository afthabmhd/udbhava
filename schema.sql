create table if not exists public.registrations (
    id bigint generated by default as identity primary key,
    submitted_at timestamptz not null default now(),
    department_id text not null,
    event_slug text not null,
    name text not null,
    college text not null,
    phone text not null,
    college_reg_no text not null,
    upi_txn_id text,
    status text not null default 'pending',
    constraint registrations_event_slug_college_reg_no_key unique (event_slug, college_reg_no),
    constraint registrations_status_check check (status in ('pending', 'verified', 'rejected'))
);

create unique index if not exists registrations_upi_txn_id_uidx
    on public.registrations (upi_txn_id)
    where upi_txn_id is not null;

create table if not exists public.test_registrations (
    id bigint generated by default as identity primary key,
    submitted_at timestamptz not null default now(),
    department_id text not null,
    event_slug text not null,
    name text not null,
    college text not null,
    phone text not null,
    college_reg_no text not null,
    upi_txn_id text,
    status text not null default 'pending',
    constraint test_registrations_event_slug_college_reg_no_key unique (event_slug, college_reg_no),
    constraint test_registrations_status_check check (status in ('pending', 'verified', 'rejected'))
);

-- School-student registration fields are optional; apply this migration to existing projects too.
alter table public.registrations alter column college drop not null;
alter table public.registrations alter column college_reg_no drop not null;
alter table public.test_registrations alter column college drop not null;
alter table public.test_registrations alter column college_reg_no drop not null;

create unique index if not exists test_registrations_upi_txn_id_uidx
    on public.test_registrations (upi_txn_id)
    where upi_txn_id is not null;

alter table public.registrations enable row level security;
alter table public.test_registrations enable row level security;

revoke all on table public.registrations, public.test_registrations from anon, authenticated;
grant all on table public.registrations, public.test_registrations to service_role;
grant usage, select on sequence public.registrations_id_seq, public.test_registrations_id_seq to service_role;
